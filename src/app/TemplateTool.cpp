int runTemplateTool(int argc, char *argv[])
{
    attachConsole();
    if (qEnvironmentVariableIsEmpty("QT_QPA_PLATFORM"))
        qputenv("QT_QPA_PLATFORM", "offscreen");
    QGuiApplication app(argc, argv);
    QCoreApplication::setApplicationName(QStringLiteral("Dafin"));
    QCoreApplication::setOrganizationName(QStringLiteral("Dafin"));
    reloadFontCatalog();
    reloadUserFonts();

    QStringList args = app.arguments().mid(1);
    QString outPath;
    const int outAt = args.indexOf(QStringLiteral("--out"));
    if (outAt >= 0) {
        outPath = args.value(outAt + 1);
        args.remove(outAt, outAt + 1 < args.size() ? 2 : 1);
    }
    const auto print = [&](const QString &text) {
        if (!outPath.isEmpty()) {
            QFile file(outPath);
            if (file.open(QIODevice::WriteOnly | QIODevice::Truncate))
                file.write(text.toUtf8());
        }
        std::fputs(text.toUtf8().constData(), stdout);
        std::fflush(stdout);
    };

    if (args.contains(QStringLiteral("--template-guide"))) {
        print(guideMarkdown());
        return 0;
    }

    if (args.contains(QStringLiteral("--check-template"))) {
        const int at = args.indexOf(QStringLiteral("--check-template"));
        const QString path = args.value(at + 1);
        if (path.isEmpty() || path.startsWith(QLatin1String("--")) || outPath.isEmpty()) {
            std::fputs("usage: dafin --check-template <file.json> --out <folder> [--text \"...\"]\n", stderr);
            return 2;
        }
#ifdef DRIFT_WITH_SKIA
        skia::TemplateCheckOptions o;
        o.outDir = outPath;
        const int textAt = args.indexOf(QStringLiteral("--text"));
        if (textAt >= 0)
            o.text = args.value(textAt + 1);
        const skia::TemplateCheckResult r = skia::runTemplateCheck(
            path, drift::appcontroller_detail::dafinTemplateEnvironment(false),
            drift::appcontroller_detail::dafinTemplateEnvironment(true), o);
        std::fputs(r.report.toUtf8().constData(), stdout);
        std::printf("\nReport: %s\n", qPrintable(QDir::toNativeSeparators(r.reportPath)));
        std::fflush(stdout);
        return r.automatedChecksPassed ? 0 : 1;
#else
        std::fputs("this build has no text renderer\n", stderr);
        return 1;
#endif
    }

    if (args.contains(QStringLiteral("--template-preview"))) {
        const auto opt = [&](const char *name, const QString &fallback) {
            const int i = args.indexOf(QLatin1String(name));
            return i >= 0 && i + 1 < args.size() ? args.at(i + 1) : fallback;
        };
        const QString path = opt("--template-preview", QString());
        if (path.isEmpty() || outPath.isEmpty()) {
            std::fputs("usage: dafin --template-preview <file.json> --out <sheet.png> [--text \"...\"] [--fps N] "
                       "[--duration-ms N] [--times ms,ms,...]\n",
                       stderr);
            return 2;
        }
        QFile file(path);
        QJsonParseError parseError;
        const QJsonDocument doc = file.open(QIODevice::ReadOnly) ? QJsonDocument::fromJson(file.readAll(), &parseError)
                                                                 : QJsonDocument();
        if (!doc.isObject()) {
            std::fprintf(stderr, "%s is not a template file\n", qPrintable(path));
            return 1;
        }
        const QList<TemplateIssue> issues =
            validateTitleTemplate(doc.object(), drift::appcontroller_detail::dafinTemplateEnvironment(false));
        for (const TemplateIssue &i : issues)
            std::fprintf(stderr, "%s\n", qPrintable(templateIssueToText(i)));
        if (hasTemplateErrors(issues))
            return 1;
#ifdef DRIFT_WITH_SKIA
        skia::ContactSheetOptions o;
        o.text = opt("--text", QString());
        o.fps = opt("--fps", QStringLiteral("30")).toInt();
        o.durationUs = TimeUs(opt("--duration-ms", QStringLiteral("3000")).toDouble() * 1000.0);
        const QString times = opt("--times", QString());
        if (!times.isEmpty())
            for (const QString &ms : times.split(QLatin1Char(',')))
                o.times << TimeUs(ms.toDouble() * 1000.0);
        const skia::ContactSheetResult r = skia::renderTemplateContactSheet(titleTemplateFromJson(doc.object()), o);
        if (!r.sheet.save(outPath)) {
            std::fprintf(stderr, "could not write %s\n", qPrintable(outPath));
            return 1;
        }
        std::printf("readable at %.1f ms; entrance %.1f of %.1f ms, exit %.1f of %.1f ms%s; wrote %s\n",
                    r.timing.readableAtUs / 1000.0, r.timing.inUs / 1000.0, r.timing.inNaturalUs / 1000.0,
                    r.timing.outUs / 1000.0, r.timing.outNaturalUs / 1000.0, r.timing.fitted ? " (fitted)" : "",
                    qPrintable(outPath));
        return 0;
#else
        std::fputs("this build has no text renderer\n", stderr);
        return 1;
#endif
    }

    const bool json = args.removeAll(QStringLiteral("--json")) > 0;
    const bool portable = args.removeAll(QStringLiteral("--portable")) > 0;
    args.removeAll(QStringLiteral("--validate-template"));
    const QStringList files = expandPaths(args);
    if (files.isEmpty()) {
        std::fputs("usage: dafin --validate-template <file.json|folder>... [--json] [--portable] [--out report.txt]\n", stderr);
        return 2;
    }

    const TemplateEnvironment env = drift::appcontroller_detail::dafinTemplateEnvironment(portable);
    bool anyErrors = false;
    QJsonArray results;
    QString text;
    for (const QString &path : files) {
        QFile file(path);
        QList<TemplateIssue> issues;
        if (!file.open(QIODevice::ReadOnly)) {
            TemplateIssue issue;
            issue.code = QStringLiteral("schema");
            issue.message = QStringLiteral("cannot open the file");
            issues << issue;
        } else {
            QJsonParseError parseError;
            const QJsonDocument doc = QJsonDocument::fromJson(file.readAll(), &parseError);
            if (!doc.isObject()) {
                TemplateIssue issue;
                issue.code = QStringLiteral("schema");
                issue.message = QStringLiteral("not valid JSON: %1 at offset %2").arg(parseError.errorString()).arg(parseError.offset);
                issues << issue;
            } else {
                issues = validateTitleTemplate(doc.object(), env);
            }
        }
        const bool ok = !hasTemplateErrors(issues);
        anyErrors = anyErrors || !ok;
        QJsonArray list;
        for (const TemplateIssue &i : issues)
            list.append(templateIssueToJson(i));
        results.append(QJsonObject{{QStringLiteral("file"), QFileInfo(path).fileName()},
                                   {QStringLiteral("ok"), ok},
                                   {QStringLiteral("issues"), list}});
        text += QStringLiteral("%1: %2\n").arg(QFileInfo(path).fileName(), ok ? QStringLiteral("OK") : QStringLiteral("NOT INSTALLABLE"));
        for (const TemplateIssue &i : issues)
            text += QStringLiteral("  ") + templateIssueToText(i) + QLatin1Char('\n');
    }
    if (json)
        print(QString::fromUtf8(QJsonDocument(QJsonObject{{QStringLiteral("format"), kTitleTemplateFormat},
                                                         {QStringLiteral("files"), results}})
                                   .toJson(QJsonDocument::Indented)));
    else
        print(text);
    return anyErrors ? 1 : 0;
}

