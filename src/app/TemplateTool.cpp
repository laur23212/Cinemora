int runTemplateTool(int argc, char *argv[])
{
    attachConsole();
    if (qEnvironmentVariableIsEmpty("QT_QPA_PLATFORM"))
        qputenv("QT_QPA_PLATFORM", "offscreen");
    QGuiApplication app(argc, argv);
    QCoreApplication::setApplicationName(QStringLiteral("Dafin"));
    QCoreApplication::setOrganizationName(QStringLiteral("Dafin"));
    reloadFontCatalog();
    reloadUserFonts();

    QStringList args = app.arguments().mid(1);
    QString outPath;
    const int outAt = args.indexOf(QStringLiteral("--out"));
    if (outAt >= 0) {
        outPath = args.value(outAt + 1);
        args.remove(outAt, outAt + 1 < args.size() ? 2 : 1);
    }
    const auto print = [&](const QString &text) {
        if (!outPath.isEmpty()) {
            QFile file(outPath);
            if (file.open(QIODevice::WriteOnly | QIODevice::Truncate))
                file.write(text.toUtf8());
        }
        std::fputs(text.toUtf8().constData(), stdout);
        std::fflush(stdout);
    };

    if (args.contains(QStringLiteral("--template-guide"))) {
        print(guideMarkdown());
        return 0;
    }

    const bool json = args.removeAll(QStringLiteral("--json")) > 0;
    const bool portable = args.removeAll(QStringLiteral("--portable")) > 0;
    args.removeAll(QStringLiteral("--validate-template"));
    const QStringList files = expandPaths(args);
    if (files.isEmpty()) {
        std::fputs("usage: dafin --validate-template <file.json|folder>... [--json] [--portable] [--out report.txt]\n", stderr);
        return 2;
    }

    const TemplateEnvironment env = drift::appcontroller_detail::dafinTemplateEnvironment(portable);
    bool anyErrors = false;
    QJsonArray results;
    QString text;
    for (const QString &path : files) {
        QFile file(path);
        QList<TemplateIssue> issues;
        if (!file.open(QIODevice::ReadOnly)) {
            TemplateIssue issue;
            issue.code = QStringLiteral("schema");
            issue.message = QStringLiteral("cannot open the file");
            issues << issue;
        } else {
            QJsonParseError parseError;
            const QJsonDocument doc = QJsonDocument::fromJson(file.readAll(), &parseError);
            if (!doc.isObject()) {
                TemplateIssue issue;
                issue.code = QStringLiteral("schema");
                issue.message = QStringLiteral("not valid JSON: %1 at offset %2").arg(parseError.errorString()).arg(parseError.offset);
                issues << issue;
            } else {
                issues = validateTitleTemplate(doc.object(), env);
            }
        }
        const bool ok = !hasTemplateErrors(issues);
        anyErrors = anyErrors || !ok;
        QJsonArray list;
        for (const TemplateIssue &i : issues)
            list.append(templateIssueToJson(i));
        results.append(QJsonObject{{QStringLiteral("file"), QFileInfo(path).fileName()},
                                   {QStringLiteral("ok"), ok},
                                   {QStringLiteral("issues"), list}});
        text += QStringLiteral("%1: %2\n").arg(QFileInfo(path).fileName(), ok ? QStringLiteral("OK") : QStringLiteral("NOT INSTALLABLE"));
        for (const TemplateIssue &i : issues)
            text += QStringLiteral("  ") + templateIssueToText(i) + QLatin1Char('\n');
    }
    if (json)
        print(QString::fromUtf8(QJsonDocument(QJsonObject{{QStringLiteral("format"), kTitleTemplateFormat},
                                                         {QStringLiteral("files"), results}})
                                   .toJson(QJsonDocument::Indented)));
    else
        print(text);
    return anyErrors ? 1 : 0;
}

