// dafin.exe is a GUI program: from a console its output goes nowhere unless it attaches to the
// console it was started from. Redirected output (> file, a pipe) needs nothing.
void attachConsole()
{
#ifdef Q_OS_WIN
    if (AttachConsole(ATTACH_PARENT_PROCESS)) {
        FILE *ignored = nullptr;
        if (_fileno(stdout) < 0)
            freopen_s(&ignored, "CONOUT$", "w", stdout);
        if (_fileno(stderr) < 0)
            freopen_s(&ignored, "CONOUT$", "w", stderr);
    }
#endif
}

QString typeName(EffectParamType t)
{
    switch (t) {
    case EffectParamType::Float:
        return QStringLiteral("scalar");
    case EffectParamType::Int:
        return QStringLiteral("scalar (whole numbers)");
    case EffectParamType::Bool:
        return QStringLiteral("bool (0/1)");
    case EffectParamType::Color:
        return QStringLiteral("color");
    case EffectParamType::Enum:
        return QStringLiteral("scalar (option index)");
    case EffectParamType::Seed:
        return QStringLiteral("scalar (seed)");
    default:
        return QStringLiteral("not bindable");
    }
}

QString guideMarkdown()
{
    QString out;
    QTextStream s(&out);
    s << "# Dafin title template reference (generated)\n\n"
      << "Generated by `dafin --template-guide` from this installation, so every list below is what "
         "this Dafin actually has. Template file format: " << kTitleTemplateFormat << ". See "
         "docs/template-authoring.md for the format itself and complete examples.\n\n";

    s << "## Control bindings\n\n| bind | type | notes |\n|---|---|---|\n";
    for (const TemplateBindingForm &f : templateBindingCatalog())
        s << "| `" << f.pattern << "` | " << f.type << " | " << f.description << " |\n";

    s << "\n## Animation presets\n\nEvery In / Out preset also takes `duration` (s), `stagger` (s), "
         "`unit` (block | character | word | line), `order` and `ease`.\n\n"
      << "| id | slots | params (type, range, default) |\n|---|---|---|\n";
    for (const TextAnimationPreset &p : TextAnimationPresetCatalog::instance().presets()) {
        if (!p.builtIn)
            continue;
        QStringList slotNames;
        for (TextAnimSlotKind k : p.slotKinds)
            slotNames << textAnimSlotKindToString(k);
        QStringList params;
        for (const TextAnimParamSpec &spec : p.params) {
            static const QStringList common{QStringLiteral("duration"), QStringLiteral("stagger"), QStringLiteral("unit"),
                                            QStringLiteral("order"), QStringLiteral("ease")};
            if (common.contains(spec.id))
                continue;
            QString line = QStringLiteral("`%1` %2").arg(spec.id, textAnimParamTypeToString(spec.type));
            if (spec.type == TextAnimParamSpec::Type::Scalar)
                line += QStringLiteral(" %1..%2%3").arg(spec.min).arg(spec.max).arg(spec.unit.isEmpty() ? QString() : QLatin1Char(' ') + spec.unit);
            if (spec.type == TextAnimParamSpec::Type::Enum)
                line += QStringLiteral(" (%1)").arg(spec.enumValues.join(QStringLiteral(" | ")));
            params << line;
        }
        s << "| `" << p.id << "` | " << slotNames.join(QStringLiteral(", ")) << " | " << params.join(QStringLiteral("; ")) << " |\n";
    }

    s << "\n## Text shader paints (`paint.kind: \"effect\"`)\n\n| id | params |\n|---|---|\n";
    for (const TextEffectSpec &e : textShaderEffectSpecs()) {
        QStringList params;
        for (const TextAnimParamSpec &spec : e.params)
            params << QStringLiteral("`%1` %2").arg(spec.id, textAnimParamTypeToString(spec.type));
        s << "| `" << e.id << "` | " << params.join(QStringLiteral(", ")) << " |\n";
    }

    s << "\n## Clip effects (for `effects[].effect`)\n\n| id | name | parameters (type, range) |\n|---|---|---|\n";
    for (const EffectPresetEntry &e : effectCatalog()) {
        if (!e.isGpu)
            continue; // the GPU packages are the ones that draw on a text clip's pixels
        QStringList params;
        for (const EffectParamSpec &p : e.meta.parameters) {
            QString line = QStringLiteral("`%1` %2").arg(p.key, typeName(p.type));
            if (p.type == EffectParamType::Float || p.type == EffectParamType::Int)
                line += QStringLiteral(" %1..%2").arg(p.min).arg(p.max);
            params << line;
        }
        s << "| `" << e.meta.id << "` | " << e.meta.displayName << " | " << params.join(QStringLiteral("; ")) << " |\n";
    }

    s << "\n## Fonts installed here for text\n\n"
         "From the Fonts Essentials add-on and the user's own fonts (system fonts also work on the machine that has them):\n\n";
    QStringList fonts;
    for (const FontFamilyEntry &f : fontCatalog())
        fonts << QStringLiteral("%1 (weights %2)").arg(f.family, [&] {
            QStringList w;
            for (int x : f.weights())
                w << QString::number(x);
            return w.join(QLatin1Char('/'));
        }());
    for (const QString &f : userFontFamilies())
        fonts << QStringLiteral("%1 (user font)").arg(f);
    for (const QString &f : fonts)
        s << "- " << f << "\n";
    if (fonts.isEmpty())
        s << "- (none: the Fonts Essentials add-on is not installed)\n";
    s << "\nA portable template should use a Fonts Essentials family and name it in `requires.fonts`.\n";
    return out;
}

QStringList expandPaths(const QStringList &paths)
{
    QStringList files;
    for (const QString &p : paths) {
        const QFileInfo info(p);
        if (info.isDir()) {
            QDirIterator it(p, {QStringLiteral("*.json")}, QDir::Files);
            while (it.hasNext())
                files << it.next();
        } else {
            files << p;
        }
    }
    files.sort();
    return files;
}

